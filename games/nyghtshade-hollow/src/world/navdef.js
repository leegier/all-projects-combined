  N('I.p', 36, 7.0); N('I.pm', 40.0, 7.0); N('I.pe', 42.3, 6.9); N('I.in', 36, 3.3); N('I.a', 36, 4.8); N('I.b', 33.2, 4.8); N('I.c', 38.8, 4.8); N('I.r', 42.7, 4.4); N('I.r2', 43.1, 6.0);
  N('R.in', 45.3, 6.0); N('R.a', 46.4, 4.3); N('R.b', 48.3, 4.3); N('R.l', 48.3, 4.55); N('R.c', 46.2, 8.0);
  // ---- west wing ----
  N('W.g1', -19.5, 0); N('W.sp', -21.6, 0); N('W.g2', -25.5, 0); N('W.c1', -28, 0); N('W.ld', -33, -0.8); N('W.c2', -38, 0); N('W.c3', -44, 0); N('W.c4', -48.5, 0);
