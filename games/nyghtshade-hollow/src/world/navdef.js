  for (let i = 0; i < 12; i++) {
    const cx = -16.5 + i * 3;
    N('N' + (i + 1), cx, -4.85); N('S' + (i + 1), cx, 4.85);
    N('NI' + (i + 1), cx + 0.2, -7.6); N('SI' + (i + 1), cx + 0.2, 7.6);
    if (i > 0 && i !== 8) N('LN' + (i + 1), cx, -3.4); if (i < 11 && i !== 3) N('LS' + (i + 1), cx, 3.4);
  }
  // upper deck + stairs (explicit)
  N('U.nw', -14.5, -4.7, 3.7); N('U.n1', -9, -4.7, 3.7); N('U.n2', -3, -4.7, 3.7); N('U.n3', 4, -4.7, 3.7); N('U.n4', 12, -4.7, 3.7);
  N('U.se', 14.5, 4.7, 3.7); N('U.s1', 9, 4.7, 3.7); N('U.s2', 3, 4.7, 3.7); N('U.s3', -4, 4.7, 3.7); N('U.s4', -12, 4.7, 3.7);
  N('St.nb', -15.5, 1.2); N('St.nt', -15.5, -3.6, 3.7);
  N('St.sb', 15.5, -1.2); N('St.st', 15.5, 3.6, 3.7);
  // ---- east wing ----
  N('E.g1', 19.5, 0); N('E.sp', 21.6, 0); N('E.g2', 25.5, 0); N('E.c1', 27, 0); N('E.cd', 29.05, -0.6); N('E.c2', 33, 0); N('E.id', 36, 0.6); N('E.c3', 42, 0); N('E.c4', 48, 0);
  N('C.in', 29.05, -3.5); N('C.a', 29.5, -4.6); N('C.b', 35, -4.6); N('C.c', 40, -4.6); N('C.m1', 31, -8.7); N('C.m2', 36, -8.7); N('C.m3', 39.5, -8.7);
